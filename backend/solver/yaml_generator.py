"""
backend/solver/yaml_generator.py
Minimal-Diff Kubernetes NetworkPolicy YAML Generator for Project Fjord.

Features:
  • Synthesizes exact minimal Kubernetes NetworkPolicy manifests from
    selected ILP remediation actions.
  • Collateral Policy Splitting: if a target workload B is currently governed
    by a shared NetworkPolicy that also selects other workloads, we split B
    out into its own dedicated managed policy before applying the
    ingress allow-list complement: AllowedSources(B) ∖ {A}.
  • All output is a valid Kubernetes NetworkPolicy (apiVersion: networking.k8s.io/v1).
  • Stamps mandatory audit note in resource annotations.
  • Never writes raw OpenCypher — graph queries are fully parameterized.
"""

from __future__ import annotations

import hashlib
import logging
from typing import Dict, List, Optional, Set, Tuple

import yaml

from backend.db.connection import db_manager
from backend.schema import RemediationType

logger = logging.getLogger(__name__)

# Annotation stamped on every Fjord-managed NetworkPolicy
FJORD_MANAGED_ANNOTATION = "fjord.security/managed-by"
FJORD_MANAGED_VALUE = "fjord-remediation-agent"
FJORD_AUDIT_ANNOTATION = "fjord.security/remediation-note"
FJORD_AUDIT_NOTE = (
    "Auto-generated by Fjord Remediation Agent. "
    "Verified via GRAPH.COPY counterfactual sandbox (VERIFIED_IN_MODEL). "
    "Review before applying to production."
)


class NetworkPolicyYAMLGenerator:
    """
    Generates minimal-diff Kubernetes NetworkPolicy manifests from
    ILP-selected RemediationActions.

    Usage:
        gen = NetworkPolicyYAMLGenerator(graph_name="prod_abc12345")
        yaml_patches = gen.generate(selected_actions)
    """

    def __init__(self, graph_name: str):
        self.graph_name = graph_name

    # ------------------------------------------------------------------
    # PUBLIC API
    # ------------------------------------------------------------------

    def generate(self, actions) -> List[str]:
        """
        Generate a list of YAML-formatted Kubernetes NetworkPolicy manifests
        for all NETWORK_POLICY_ADD / NETWORK_POLICY_PATCH actions.

        Args:
            actions: List[RemediationAction] as selected by the ILP solver.

        Returns:
            List of YAML strings (one per unique target workload).
        """
        # Group block edges by destination workload (the workload being protected)
        # Key: dst_workload_id → set of src_workload_ids to block
        block_map: Dict[str, Set[str]] = {}

        for action in actions:
            if action.remediation_type not in (
                RemediationType.NETWORK_POLICY_ADD,
                RemediationType.NETWORK_POLICY_PATCH,
            ):
                continue
            # Extract src and dst from mutation_params
            src_id = action.mutation_params.get("src_id", "")
            dst_id = action.mutation_params.get("dst_id", "")
            if src_id and dst_id:
                block_map.setdefault(dst_id, set()).add(src_id)

        yaml_patches: List[str] = []
        for dst_id, blocked_sources in block_map.items():
            try:
                patches = self._generate_policies_for_workload(dst_id, blocked_sources)
                yaml_patches.extend(patches)
            except Exception as exc:
                logger.error("Failed to generate NetworkPolicy for %s: %s", dst_id, exc)

        logger.info(
            "Generated %d NetworkPolicy manifests for graph %s",
            len(yaml_patches), self.graph_name,
        )
        return yaml_patches

    # ------------------------------------------------------------------
    # INTERNAL HELPERS
    # ------------------------------------------------------------------

    def _generate_policies_for_workload(
        self,
        dst_workload_id: str,
        blocked_sources: Set[str],
    ) -> List[str]:
        """
        Synthesise NetworkPolicy manifests covering the 3 cases:
        Case 1: No existing policy on target workload B -> create dedicated policy for B.
        Case 2: 1 dedicated policy on B -> update/replace rules for B.
        Case 3: Permissive policy shared by B and collateral workload C -> emit two manifests:
                (a) Narrowed shared policy excluding B (e.g. targeting C only).
                (b) New dedicated policy on B restricting ingress from blocked callers.
        """
        dst_ns, dst_name = _parse_workload_id(dst_workload_id)

        # Determine labels of destination workload
        dst_labels = self._get_workload_labels(dst_workload_id)
        if not dst_labels:
            dst_labels = {"app": dst_name}

        # Compute the current allowed ingress sources (minus blocked ones)
        current_allowed = self._get_current_ingress_sources(dst_workload_id)
        allow_sources = current_allowed - blocked_sources

        # Build ingress rules: allow remaining sources
        ingress_rules = []
        for src_id in sorted(allow_sources):
            src_ns, src_name = _parse_workload_id(src_id)
            src_labels = self._get_workload_labels(src_id)
            if not src_labels:
                src_labels = {"app": src_name}
            rule = self._build_ingress_rule(src_labels, src_ns, dst_ns)
            ingress_rules.append(rule)

        # Check for shared policy (Case 3)
        shared_info = self._find_shared_policy_info(dst_workload_id, dst_labels)
        manifests = []

        if shared_info:
            # Case 3: Shared policy detected
            shared_name, collateral_workloads = shared_info
            # Manifest 3a: Narrowed shared policy targeting collateral workloads only
            for coll_id in collateral_workloads:
                coll_ns, coll_name = _parse_workload_id(coll_id)
                coll_labels = self._get_workload_labels(coll_id) or {"app": coll_name}
                narrowed_manifest = {
                    "apiVersion": "networking.k8s.io/v1",
                    "kind": "NetworkPolicy",
                    "metadata": {
                        "name": f"{shared_name}-narrowed",
                        "namespace": coll_ns,
                        "annotations": {
                            FJORD_MANAGED_ANNOTATION: FJORD_MANAGED_VALUE,
                            FJORD_AUDIT_ANNOTATION: f"Collateral split: Narrowed '{shared_name}' to retain protection on collateral workload '{coll_name}' while separating '{dst_name}'."
                        },
                        "labels": {
                            "fjord.security/managed": "true",
                            "fjord.security/split-from": shared_name,
                        }
                    },
                    "spec": {
                        "podSelector": {"matchLabels": coll_labels},
                        "policyTypes": ["Ingress"],
                        "ingress": [] # Retain default baseline
                    }
                }
                manifests.append(yaml.dump(narrowed_manifest, default_flow_style=False, sort_keys=False))

            audit_note = (
                f"{FJORD_AUDIT_NOTE} [Case 3: Collateral Split] Target '{dst_name}' separated "
                f"from shared policy '{shared_name}'."
            )
        else:
            # Case 1 (no existing policy) or Case 2 (dedicated policy)
            existing_dedicated = self._find_dedicated_policy(dst_workload_id)
            if existing_dedicated:
                audit_note = f"{FJORD_AUDIT_NOTE} [Case 2: Dedicated Policy Modified] Updated '{existing_dedicated}'."
            else:
                audit_note = f"{FJORD_AUDIT_NOTE} [Case 1: Dedicated Policy Created] New policy for '{dst_name}'."

        # Manifest: Dedicated policy for dst_workload_id
        short_hash = hashlib.sha1(
            (dst_workload_id + ",".join(sorted(blocked_sources))).encode()
        ).hexdigest()[:8]
        policy_name = f"fjord-managed-{dst_name}-{short_hash}"

        dedicated_manifest = {
            "apiVersion": "networking.k8s.io/v1",
            "kind": "NetworkPolicy",
            "metadata": {
                "name": policy_name,
                "namespace": dst_ns,
                "annotations": {
                    FJORD_MANAGED_ANNOTATION: FJORD_MANAGED_VALUE,
                    FJORD_AUDIT_ANNOTATION: audit_note,
                },
                "labels": {
                    "fjord.security/managed": "true",
                    "fjord.security/target-workload": dst_name,
                },
            },
            "spec": {
                "podSelector": {"matchLabels": dst_labels},
                "policyTypes": ["Ingress"],
                "ingress": ingress_rules,
            },
        }
        manifests.append(yaml.dump(dedicated_manifest, default_flow_style=False, sort_keys=False))

        return manifests

    def _build_ingress_rule(
        self,
        src_labels: Dict[str, str],
        src_ns: str,
        dst_ns: str,
    ) -> Dict:
        """Build a single Kubernetes NetworkPolicy ingress rule entry."""
        from_entries = [{"podSelector": {"matchLabels": src_labels}}]
        # Add namespaceSelector only if cross-namespace
        if src_ns != dst_ns:
            from_entries.insert(0, {"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": src_ns}}})
            # Combine pod + namespace selector via nested from entry
            from_entries = [
                {
                    "namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": src_ns}},
                    "podSelector": {"matchLabels": src_labels},
                }
            ]
        return {"from": from_entries}

    def _get_workload_labels(self, workload_id: str) -> Dict[str, str]:
        """Query FalkorDB for a workload's label set."""
        rows = db_manager.query(
            self.graph_name,
            "MATCH (w:Workload {id: $wid}) RETURN w.labels AS labels",
            params={"wid": workload_id},
            read_only=True,
        )
        if rows and rows[0][0]:
            raw = rows[0][0]
            if isinstance(raw, dict):
                return raw
            # If stored as a string representation, attempt basic parsing
            try:
                import json
                return json.loads(raw)
            except Exception:
                return {}
        return {}

    def _get_current_ingress_sources(self, dst_workload_id: str) -> Set[str]:
        """
        Return the set of workload IDs that currently have CAN_REACH_NET
        to the destination workload (i.e., current allowed ingress traffic).
        """
        rows = db_manager.query(
            self.graph_name,
            """
            MATCH (src:Workload)-[:CAN_REACH_NET]->(dst:Workload {id: $dst_id})
            RETURN src.id AS src_id
            """,
            params={"dst_id": dst_workload_id},
            read_only=True,
        )
        return {str(r[0]) for r in rows if r[0]}

    def _find_shared_policy(
        self,
        workload_id: str,
        workload_labels: Dict[str, str],
    ) -> Optional[str]:
        """
        Check if this workload is currently selected by a NetworkPolicy node
        that also selects other workloads (shared policy — collateral split needed).
        Returns the shared policy name if found, else None.
        """
        rows = db_manager.query(
            self.graph_name,
            """
            MATCH (np:NetworkPolicy)-[:SELECTS]->(w:Workload {id: $wid})
            RETURN np.name AS np_name, np.id AS np_id
            """,
            params={"wid": workload_id},
            read_only=True,
        )
        for row in rows:
            np_name = str(row[0]) if row[0] else str(row[1])
            # Check if this NP also selects other workloads
            other_rows = db_manager.query(
                self.graph_name,
                """
                MATCH (np:NetworkPolicy {name: $np_name})-[:SELECTS]->(w:Workload)
                WHERE w.id <> $wid
                RETURN count(w) AS others
                """,
                params={"np_name": np_name, "wid": workload_id},
                read_only=True,
            )
            if other_rows and other_rows[0][0] and int(other_rows[0][0]) > 0:
                return np_name
        return None


# ---------------------------------------------------------------------------
# Private utilities
# ---------------------------------------------------------------------------

def _parse_workload_id(workload_id: str) -> Tuple[str, str]:
    """Parse '{namespace}/{name}' into (namespace, name)."""
    parts = workload_id.split("/", 1)
    if len(parts) == 2:
        return parts[0], parts[1]
    return "default", workload_id
